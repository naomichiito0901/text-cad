const { chromium } = require('playwright');
const S = require('path').join(process.env.CAD_OUT || '/tmp/cad-out', '/'); require('fs').mkdirSync(S, { recursive: true });
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const ctx = await b.newContext({ viewport: { width: 1440, height: 860 }, acceptDownloads: true });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  p.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
  await p.goto('file://' + require('path').resolve(__dirname, '../dist/index.html'));
  await p.waitForTimeout(500);
  const st = async () => (await p.textContent('#status')) + ' | err:' + ((await p.textContent('#error')) || '-');
  for (const n of [1, 2, 3, 4, 5, 6]) {
    await p.click(`[data-step="${n}"]`); await p.waitForTimeout(500);
    console.log('step', n, await st());
    await p.screenshot({ path: S + `step${n}.png` });
  }
  await p.click('[data-step="5"]'); await p.waitForTimeout(300);
  console.log('rules NG:', await p.$$eval('tr.row-error, tr.row-warn', t => t.map(x => x.innerText.replace(/\s+/g, ' ').slice(0, 90))));
  await p.fill('#appr-name', '検図者A');
  if (await p.$('#appr-ack')) await p.check('#appr-ack');
  await p.click('[data-act="approve"]'); await p.waitForTimeout(300);
  console.log('approve ->', (await p.textContent('.approve')).replace(/\s+/g, ' '));
  await p.screenshot({ path: S + 'step5-approved.png' });
  await p.click('[data-step="6"]'); await p.waitForTimeout(300);
  let [d] = await Promise.all([p.waitForEvent('download'), p.click('[data-act="zip"]')]);
  await d.saveAs(S + 'pkg.zip'); console.log('zip', d.suggestedFilename());
  await p.waitForTimeout(300);
  console.log('step6:', (await p.textContent('#panel')).replace(/\s+/g, ' ').slice(0, 200));
  await p.fill('#rev-note', '穴径 φ8 → φ9'); await p.click('[data-act="revise"]'); await p.waitForTimeout(500);
  console.log('after revise status:', await st(), '| rev line:', (await p.inputValue('#editor')).match(/rev:.*/)[0]);
  await p.click('[data-step="4"]'); await p.waitForTimeout(500);
  await p.screenshot({ path: S + 'step4-rev.png' });
  await p.click('[data-step="5"]'); await p.waitForTimeout(300);
  console.log('approval after revise:', (await p.textContent('.approve')).replace(/\s+/g, ' ').slice(0, 80));
  let y = (await p.inputValue('#editor')).replace('at: [80, 25, 10]', 'at: [80, 25, 5]');
  await p.fill('#editor', y); await p.waitForTimeout(600);
  await p.click('[data-step="3"]'); await p.waitForTimeout(600);
  console.log('interference:', await st(), '|', (await p.textContent('#resultbar')).replace(/\s+/g, ' ').slice(0, 160));
  await p.screenshot({ path: S + 'step3-hit.png' });
  await p.click('[data-step="5"]'); await p.waitForTimeout(300);
  console.log('approve disabled:', await p.$eval('[data-act="approve"]', e => e.disabled));
  await p.click('[data-step="1"]');
  await p.fill('#editor', 'domain: mechanical\nmode: 3d\ndimensions: none\nparts:\n  - box: {name: a, size: [30, 20, 5]}\n  - hole: {target: a, diameter: 8, at: [5, 10]}\n'); await p.waitForTimeout(600);
  console.log('minimal step1:', await st());
  await p.screenshot({ path: S + 'min-step1.png' });
  await p.click('[data-step="5"]'); await p.waitForTimeout(300);
  console.log('minimal NG:', await p.$$eval('tr.row-error', t => t.map(x => x.innerText.replace(/\s+/g, ' ').slice(0, 110))));
  await p.click('[data-step="4"]'); await p.waitForTimeout(400);
  console.log('step4 minimal:', await st());
  await p.click('#about-open'); await p.waitForTimeout(200);
  const about = await p.textContent('#about-text');
  const aboutOk = ['MIT License', 'three', 'js-yaml', '@jscad/modeling'].every((k) => about.includes(k)) && about.includes('Copyright (c) 2026');
  console.log('about dialog has licenses:', aboutOk);
  if (!aboutOk) errs.push('about dialog: ライセンス文が表示されません');
  console.log('ERRORS', errs);
  await b.close();
})();
